"""Export Clawd's poses and the favicon from the clawd skill's library.

Clawd is never drawn by hand on this site: every grid comes from the
approved grids of the AIOS clawd skill (.agents/skills/clawd/scripts/clawd.py).
This script writes:

  js/clawd-sprites.js    every documented pose, one string per row
  favicon.png            the "icon" preset: 24 x 24 cells at x4 = 96 px
  favicon.svg            the same cells as squares (sharp at any size)
  apple-touch-icon.png   180 x 180, Clawd at x7 on white

Run it from anywhere, giving the path of the AIOS folder:

  python3 tools/make-clawd.py /path/to/AIOS
"""
import itertools
import sys
from pathlib import Path

sys.dont_write_bytecode = True
SITE = Path(__file__).resolve().parents[1]
if len(sys.argv) != 2:
    sys.exit(__doc__)
sys.path.insert(0, str(Path(sys.argv[1]) / ".agents/skills/clawd/scripts"))
import clawd as c  # noqa: E402
from PIL import Image  # noqa: E402


def key(view, face, arm, crouch, legs):
    """Pose name used by the site, e.g. "side_right/typing/crouch"."""
    parts = [view]
    if face != "normal":
        parts.append(face)
    if arm:
        parts.append(arm)
    if crouch:
        parts.append("crouch")
    if legs:
        parts.append("legs" + legs)
    return "/".join(parts)


# Every combination the library accepts for the two views the stage uses.
poses = {}
for view in ("front", "side_right"):
    arms = [None, "left_up", "right_up"] if view == "front" else [None, "typing"]
    legs_list = (None,) if view == "front" else (None, "A", "B")   # Clawd only walks in profile
    for face, arm, crouch, legs in itertools.product(c.FACES, arms, (0, 1), legs_list):
        try:
            grid = c.pose(view, face, arm, crouch, legs)
        except ValueError:
            continue  # not a documented move for this view
        poses[key(view, face, arm, crouch, legs)] = grid

hexa = lambda col: "#%02x%02x%02x" % col[:3]
lines = [
    "// Clawd's poses, generated by tools/make-clawd.py from the approved grids",
    "// of the AIOS clawd skill. Do not edit by hand: run the script again.",
    '// One string per row: "#" body, "d" shade, "k" eye, "." empty.',
    "// Pose names: view / face / arm / crouch / legs, e.g. \"side_right/typing\".",
    "",
    "const CLAWD_COLORS = { \"#\": \"%s\", \"d\": \"%s\", \"k\": \"%s\" };" % (
        hexa(c.CLAWD), hexa(c.CLAWD_DK), hexa(c.EYE)),
    "",
    "const CLAWD_POSES = {",
]
for name, grid in poses.items():
    rows = ",".join('"%s"' % r for r in grid)
    lines.append('  "%s": [%s],' % (name, rows))
lines += ["};", ""]
(SITE / "js/clawd-sprites.js").write_text("\n".join(lines))
print(len(poses), "poses ->", SITE / "js/clawd-sprites.js")

# Favicon: the icon preset (front view, one cell of margin on each side).
icon = c.icon_canvas()
c.stamp(icon, c.pose("front"), 1, 4)
c.export(icon, SITE / "favicon.png", "icon")

# The same cells as an SVG: one rectangle per run of same-colour cells.
rects = []
for y in range(icon.h):
    x = 0
    while x < icon.w:
        col = icon.px[x, y]
        end = x
        while end < icon.w and icon.px[end, y] == col:
            end += 1
        if col[3]:
            rects.append('<rect x="%d" y="%d" width="%d" height="1" fill="%s"/>' % (x, y, end - x, hexa(col)))
        x = end
svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" shape-rendering="crispEdges">'
       + "".join(rects) + "</svg>\n")
(SITE / "favicon.svg").write_text(svg)

# Home-screen icon for iPhones: 180 px, Clawd at x7 on white (no transparency there).
touch = Image.new("RGBA", (180, 180), (255, 255, 255, 255))
cv = c.Canvas(22, 16)
c.stamp(cv, c.pose("front"), 0, 0)
art = cv.scaled(7)
touch.alpha_composite(art, ((180 - art.width) // 2, (180 - art.height) // 2))
touch.convert("RGB").save(SITE / "apple-touch-icon.png", optimize=True)
print("favicon.png, favicon.svg, apple-touch-icon.png written")
