"""Export Clawd's poses for the contribution graph from the clawd skill's library.

Clawd is never drawn by hand on this site: every grid comes from the
approved grids of the AIOS clawd skill (.agents/skills/clawd/scripts/clawd.py).
This script writes:

  js/clawd-sprites.js    the poses the contribution graph uses, one string per row

The favicons and the share image show the yannworks logo, not Clawd: they
come from tools/make-logo.mjs.

Run it from anywhere, giving the path of the AIOS folder:

  python3 tools/make-clawd.py /path/to/AIOS
"""
import itertools
import sys
from pathlib import Path

sys.dont_write_bytecode = True
SITE = Path(__file__).resolve().parents[1]
if len(sys.argv) != 2:
    sys.exit(__doc__)
sys.path.insert(0, str(Path(sys.argv[1]) / ".agents/skills/clawd/scripts"))
import clawd as c  # noqa: E402


def key(view, face, arm, crouch, legs):
    """Pose name used by the site, e.g. "side_right/typing/crouch"."""
    parts = [view]
    if face != "normal":
        parts.append(face)
    if arm:
        parts.append(arm)
    if crouch:
        parts.append("crouch")
    if legs:
        parts.append("legs" + legs)
    return "/".join(parts)


# The poses the graph uses (js/activity.js): from the front, every face, the arm
# raised on the left (a wave) and the crouch of a bounce; in profile, the walk.
poses = {}
for view in ("front", "side_right"):
    arms = [None, "left_up"] if view == "front" else [None]
    faces = c.FACES if view == "front" else ["normal"]
    legs_list = (None,) if view == "front" else (None, "A", "B")   # Clawd only walks in profile
    for face, arm, crouch, legs in itertools.product(faces, arms, (0, 1), legs_list):
        try:
            grid = c.pose(view, face, arm, crouch, legs)
        except ValueError:
            continue  # not a documented move for this view
        poses[key(view, face, arm, crouch, legs)] = grid

hexa = lambda col: "#%02x%02x%02x" % col[:3]
lines = [
    "// Clawd's poses, generated by tools/make-clawd.py from the approved grids",
    "// of the AIOS clawd skill. Do not edit by hand: run the script again.",
    '// One string per row: "#" body, "d" shade, "k" eye, "." empty.',
    "// Pose names: view / face / arm / crouch / legs, e.g. \"side_right/typing\".",
    "",
    "const CLAWD_COLORS = { \"#\": \"%s\", \"d\": \"%s\", \"k\": \"%s\" };" % (
        hexa(c.CLAWD), hexa(c.CLAWD_DK), hexa(c.EYE)),
    "",
    "const CLAWD_POSES = {",
]
for name, grid in poses.items():
    rows = ",".join('"%s"' % r for r in grid)
    lines.append('  "%s": [%s],' % (name, rows))
lines += ["};", ""]
(SITE / "js/clawd-sprites.js").write_text("\n".join(lines))
print(len(poses), "poses ->", SITE / "js/clawd-sprites.js")
